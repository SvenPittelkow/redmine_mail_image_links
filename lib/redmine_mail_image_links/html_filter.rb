require 'cgi'

module RedmineMailImageLinks
  # Pure-Ruby HTML filter (no Rails dependency) that replaces <img> tags with
  # a link to the image. The HTML it works on is generated by Redmine's text
  # formatters, so a targeted regex approach is sufficient and keeps the rest
  # of the email markup byte-for-byte unchanged.
  class HtmlFilter
    DEFAULT_LINK_TEXT = '[Image]'

    # <a ...><img ...></a> as produced by the {{thumbnail}} macro or by
    # Textile/Markdown "linked image" syntax.
    LINKED_IMG = %r{(<a\b[^>]*>)\s*<img\b[^>]*>\s*(</a>)}im
    IMG        = /<img\b[^>]*>/im
    SRC        = /\ssrc\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]+))/im
    LINKABLE   = %r{\Ahttps?://}i

    attr_reader :link_text

    def initialize(link_text: DEFAULT_LINK_TEXT)
      text = link_text.to_s.strip
      @link_text = text.empty? ? DEFAULT_LINK_TEXT : text
    end

    # Returns the filtered HTML. Returns the very same string object when
    # there is nothing to replace.
    def call(html)
      return html if html.nil? || !html.match?(/<img\b/i)

      label = CGI.escapeHTML(link_text)
      result = html.gsub(LINKED_IMG) { "#{Regexp.last_match(1)}#{label}#{Regexp.last_match(2)}" }
      result.gsub(IMG) { |tag| replacement_for(tag, label) }
    end

    private

    def replacement_for(tag, label)
      src = extract_src(tag)
      # Only link to real web URLs. cid:/data: images or relative paths cannot
      # be opened from a mail client, so only the label is kept.
      return label unless src&.match?(LINKABLE)

      %(<a href="#{src.gsub('"', '&quot;')}">#{label}</a>)
    end

    def extract_src(tag)
      m = SRC.match(tag)
      return nil unless m

      (m[1] || m[2] || m[3]).to_s.strip
    end
  end
end
